package micropanel

// Camera-number dot matrix, output report 0x11: 7 rows x 10 columns, 2 bits
// per pixel, pixel p = row*10 + col stored LSB-first (byte p>>2, bits 2*(p&3)).

// Pixel colours.
const (
	PixOff   = 0
	PixRed   = 1
	PixGreen = 2
	PixAmber = 3
)

const (
	MatrixRows = 7
	MatrixCols = 10
)

// Single-character font (bit k = column k), centred, as in ATEM Software Control.
var matrixFont1 = [10][7]uint16{
	{0x70, 0x88, 0x88, 0x88, 0x88, 0x88, 0x70},
	{0x20, 0x30, 0x20, 0x20, 0x20, 0x20, 0x70},
	{0x70, 0x88, 0x80, 0x60, 0x10, 0x08, 0xF8},
	{0x70, 0x88, 0x80, 0x60, 0x80, 0x88, 0x70},
	{0x40, 0x60, 0x50, 0x48, 0xF8, 0x40, 0x40},
	{0xF8, 0x08, 0x08, 0xF0, 0x80, 0x88, 0x70},
	{0x70, 0x88, 0x08, 0x78, 0x88, 0x88, 0x70},
	{0xF8, 0x80, 0x40, 0x20, 0x10, 0x10, 0x10},
	{0x70, 0x88, 0x88, 0x70, 0x88, 0x88, 0x70},
	{0x70, 0x88, 0x88, 0xF0, 0x80, 0x88, 0x70},
}

// Narrow font for two-digit numbers: 4 px wide, second digit shifted 5 columns.
var matrixFont2 = [10][7]uint16{
	{0x06, 0x09, 0x09, 0x09, 0x09, 0x09, 0x06},
	{0x04, 0x06, 0x04, 0x04, 0x04, 0x04, 0x0E},
	{0x06, 0x09, 0x08, 0x04, 0x02, 0x01, 0x0F},
	{0x06, 0x09, 0x08, 0x06, 0x08, 0x09, 0x06},
	{0x08, 0x0C, 0x0A, 0x09, 0x0F, 0x08, 0x08},
	{0x0F, 0x01, 0x01, 0x0E, 0x08, 0x09, 0x06},
	{0x06, 0x09, 0x01, 0x0E, 0x09, 0x09, 0x06},
	{0x0F, 0x08, 0x04, 0x02, 0x02, 0x02, 0x02},
	{0x06, 0x09, 0x09, 0x06, 0x09, 0x09, 0x06},
	{0x06, 0x09, 0x09, 0x0E, 0x08, 0x09, 0x06},
}

// Matrix is the pixel buffer of report 0x11.
type Matrix [32]byte

// Set sets pixel (row, col) to a colour.
func (m *Matrix) Set(row, col int, colour byte) {
	if row < 0 || row >= MatrixRows || col < 0 || col >= MatrixCols {
		return
	}
	p := row*MatrixCols + col
	shift := 2 * (p & 3)
	m[p>>2] = m[p>>2]&^(3<<shift) | (colour&3)<<shift
}

// MatrixNumber renders 0..99 in the given colour, like ATEM Software Control.
func MatrixNumber(n int, colour byte) Matrix {
	var m Matrix
	draw := func(rows [7]uint16, shift int) {
		for r, bits := range rows {
			for c := 0; c < MatrixCols; c++ {
				if bits>>c&1 == 1 {
					m.Set(r, c+shift, colour)
				}
			}
		}
	}
	switch {
	case n >= 0 && n <= 9:
		draw(matrixFont1[n], 0)
	case n >= 10 && n <= 99:
		draw(matrixFont2[n/10], 0)
		draw(matrixFont2[n%10], 5)
	}
	return m
}

// MatrixDigit renders a camera number in red.
func MatrixDigit(n int) [32]byte { return MatrixNumber(n, PixRed) }
